/** Ids of the life cards a finished life earns (catalog order). */
export function evaluateLife(state) {
  const F = lifeFacts(state);
  const out = [];
  for (const a of [...LIFE_CARDS, ...RARE_CARDS]) {
    try { if (a.test(F)) out.push(a.id); } catch { /* a malformed old save never breaks the death screen */ }
  }
  return out;
}

/** Ids of the collection cards earned by `meta` = { lives, sexes:[], countries:[], regions:[], cardCount }. */
export function evaluateMeta(meta) {
  const M = { lives: 0, sexes: [], countries: [], regions: [], cardCount: 0, ...(isObj(meta) ? meta : {}) };
  return META_CARDS.filter((a) => { try { return a.test(M); } catch { return false; } }).map((a) => a.id);
}
