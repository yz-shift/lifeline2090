const isNum = (x) => typeof x === 'number' && Number.isFinite(x);
const num = (x, d = 0) => (x !== null && x !== '' && isNum(+x) ? +x : d);
const isObj = (x) => !!x && typeof x === 'object' && !Array.isArray(x);
const arr = (x) => (Array.isArray(x) ? x : []);

/** Facts about a finished life that the checks read (pure; tolerant of old saves). */
export function lifeFacts(state) {
  const s = isObj(state) ? state : {};
  const b = isObj(s.birth) ? s.birth : {};
  const p = isObj(s.person) ? s.person : {};
  const d = isObj(s.dead) ? s.dead : {};
  const flags = isObj(p.flags) ? p.flags : {};
  const money = isObj(p.money) ? p.money : {};
  const pf = isObj(money.portfolio) ? money.portfolio : {};
  const rel = isObj(p.relationship) ? p.relationship : {};
  const edu = isObj(p.education) ? p.education : {};
  const career = isObj(p.career) ? p.career : {};
  const stats = isObj(s.stats) ? s.stats : {};
  const history = arr(s.history).filter(isObj);
  const log = arr(s.log).filter(isObj);
  const kids = arr(p.children).filter(isObj);
  const pets = arr(p.pets).filter(isObj);
  const by = num(b.year, num(s.year) - num(s.age));
  const age = num(d.age, num(s.age));
  const born = b.country || p.country || '';
  const countries = new Set([born, p.country, ...history.map((r) => r.country)].filter(Boolean));
  let worth = num(money.cash);
  for (const k of Object.keys(pf)) worth += Math.max(0, num(pf[k]));
  worth -= num(money.debt);
  const wed = num(flags['rel:wed'], NaN);
  const allFive = history.some((r) => isObj(r.stats) && ['health', 'happiness', 'knowledge', 'relationships', 'wealth'].every((k) => num(r.stats[k]) >= 85));
  const notes = arr(s.notes).filter(isObj);
  let pct = num(d.percentile, NaN);
  if (pct <= 1) pct *= 100;
  return {
    by, age, dy: num(d.year, by + age), dead: !!s.dead, born, iso: p.country || born, sex: p.sex || b.sex,
    familyPct: num(b.familyPct, num(p.familyPct, 0.5)), parentsEdu: b.parentsEdu || '',
    countries, migrated: !!(p.country && born && p.country !== born),
    edu: edu.level || 'none', exams: arr(edu.exams).filter(isObj),
    career: career.status || '', incomePct: num(career.incomePct), retiredYear: num(flags.retiredYear, NaN),
    worth, debt: num(money.debt), stats, flags,
    ev: (id) => flags['ev:' + id] != null,
    rel: rel.status || 'single', wed,
    married: ['married', 'widowed', 'divorced'].includes(rel.status) || isNum(wed),
    divorced: rel.status === 'divorced' || log.some((e) => e.kind === 'milestone' && /离婚了/.test(String(e.text || ''))),
    kids, sons: kids.filter((k) => k.sex === 'male').length, daughters: kids.filter((k) => k.sex === 'female').length,
    pets, petKinds: new Set(pets.map((x) => x.kind)),
    rare: new Set(arr(s.rare).filter(isObj).map((r) => r.id)),
    pct, le: num(d.lifeExpAtBirth, NaN), allFive,
    customDecisions: arr(s.decisions).filter((x) => isObj(x) && x.custom).length,
    named: log.filter((e) => arr(e.tags).includes('naming')).length,
    smallMine: log.filter((e) => arr(e.tags).includes('small') && !arr(e.tags).includes('auto')).length,
    focusMine: history.filter((r) => r.focus && r.focusAuto === false).length,
    notes: notes.filter((n) => n.kind !== 'final').length,
    finalNote: notes.some((n) => n.kind === 'final' && String(n.text || '').trim() !== ''),
    stars: arr(s.stars).length,
    gaokao: arr(s.decisions).some((x) => isObj(x) && /高考/.test(String(x.title || ''))) || arr(edu.exams).some((x) => isObj(x) && x.name === '高考'),
    civilTried: arr(s.decisions).some((x) => isObj(x) && /考公|公务员|公职/.test(String(x.choice || ''))),
    civil: log.some((e) => /你考上了公务员/.test(String(e.text || ''))),
  };
}

