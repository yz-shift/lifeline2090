/** Text of a template field (string, list or function of f). */
function resolveText(v, f, R) {
  let t = v;
  try { if (typeof t === 'function') t = t(f); } catch { t = ''; }
  if (Array.isArray(t)) t = R.pick(t);
  return typeof t === 'string' ? t : '';
}

function fill(text, f, R, vars) {
  if (!text) return '';
  const fillText = typeof EV.fillText === 'function' ? EV.fillText : null;
  let out = fillText ? fillText(text, f.state, f.ctx, R, vars, f) : text;
  // anything the shared filler did not know (or when it is missing)
  out = out.replace(/\{(\w+)\}/g, (m, k) => (vars && vars[k] != null ? String(vars[k]) : ''));
  return out.replace(/\s+/g, ' ').trim();
}

/** Short hint for an option from its effects (≤ 16 chars), unless the option carries its own. */
export function optionHint(opt) {
  if (opt && typeof opt.hint === 'string' && opt.hint) return opt.hint.slice(0, 16);
  const fx = (opt && opt.fx) || [];
  const stats = { health: num(fx[0]), happiness: num(fx[1]), knowledge: num(fx[2]), relationships: num(fx[3]) };
  const words = effectWords(stats, 2);
  const w = num(fx[4]);
  if (opt && opt.alloc) words.push('调整理财方式');
  else if (w <= -1) words.push('花一笔钱');
  else if (w < 0) words.push('花点钱');
  else if (w >= 1) words.push('多攒些钱');
  else if (w > 0) words.push('省点钱');
  let h = words.join(' ');
  if (h.length > 16) h = words.slice(0, 2).join(' ');
  return h || '平平常常';
}

function eligibleOpts(t, f) {
  return t.opts.filter((op) => {
    if (typeof op.req !== 'function') return true;
    try { return !!op.req(f); } catch { return false; }
  }).slice(0, 3);
}

/**
 * Pick a small choice for this life-year (f = lifeFacts), or null. seen = {templateId: lastYear}.
 * The returned SmallChoice (CONTRACT §10) also carries `tpl` (template id), `opts` (the template option index for each
 * option id) and `vars` (names filled into the text), so the resolution can be told with the same words.
 */
export function pickSmallChoice(f, seen, rng) {
  if (!f) return null;
  const R = rng && typeof rng.next === 'function' ? rng : new Rng(hashString(`small|${f.year}`));
  const S = isObj(seen) ? seen : {};
  const cands = [];
  const weights = [];
  for (const t of L) {
    const last = S[t.id];
    if (last != null && (!t.cd || f.year - num(last, 0) < t.cd)) continue;
    let w;
    try { w = t.when(f); } catch { w = false; }
    w = w === true ? 1 : isNum(w) && w > 0 ? w : 0;
    if (!w) continue;
    if (eligibleOpts(t, f).length < 2) continue;
    cands.push(t);
    weights.push(w * t.w);
  }
  if (!cands.length) return null;
  const t = R.weighted(cands, weights);
  if (!t) return null;
  return buildChoice(t, f, R);
}

function buildChoice(t, f, R) {
  const p = (f.state && f.state.person) || {};
  const personName = typeof EV.personName === 'function' ? EV.personName : null;
  const vars = {
    friend: personName ? personName(f.data, f.iso, f.m ? 'male' : 'female', R) : '老朋友',
    petname: petName(f.iso, R),
    abroad: R.pick(ABROAD[f.reg] || ABROAD.WEU),
  };
  if (vars.friend === p.name) vars.friend = '老朋友';
  const opts = eligibleOpts(t, f);
  const ids = ['a', 'b', 'c'];
  const options = [];
  const index = {};
  opts.forEach((op, i) => {
    const label = fill(resolveText(op.label, f, R), f, R, vars).slice(0, 10);
    options.push({ id: ids[i], label, hint: optionHint(op) });
    index[ids[i]] = t.opts.indexOf(op);
  });
  const title = fill(resolveText(t.title, f, R), f, R, vars).slice(0, 14);
  const text = fill(resolveText(t.text, f, R), f, R, vars);
  if (!title || !text || options.some((x) => !x.label) || /\{\w+\}/.test(title + text)) return null;
  return {
    id: `s-${t.id}-${f.year}`, tpl: t.id, year: f.year, age: f.age, kind: t.kind, title, text, options,
    expiresYear: f.year + 1, opts: index, vars,
  };
}

/** The template option behind an option id of a SmallChoice, or null. */
export function smallOption(choice, optionId) {
  const t = choice && BY_ID.get(choice.tpl);
  if (!t) return null;
  const idx = choice.opts && isNum(choice.opts[optionId]) ? choice.opts[optionId] : ['a', 'b', 'c'].indexOf(optionId);
  return t.opts[idx] || null;
}

/**
 * The option an automatic resolution picks: the option's popularity (w) × the texture's tag multipliers.
 * Deterministic for a life and a choice.
 */
export function autoSmallOption(choice, texture, seedKey) {
  const t = choice && BY_ID.get(choice.tpl);
  const list = choice && Array.isArray(choice.options) ? choice.options : [];
  if (!t || !list.length) return list[0] ? list[0].id : null;
  const T = TEXTURES[texture] || TEXTURES.normal;
  const R = new Rng(hashString(`${seedKey || ''}|smallauto|${choice.id}|${texture}`));
  const pick = R.weighted(list, (x) => {
    const op = smallOption(choice, x.id);
    if (!op) return 0.01;
    let w = num(op.w, 1);
    for (const tag of op.tags || []) w *= num(T.tags[tag], 1);
    return Math.max(0.01, w);
  });
  return pick ? pick.id : list[0].id;
}

/** The result sentence of an option, filled with the choice's names. */
export function smallResult(choice, opt, f, rng) {
  const R = rng && typeof rng.next === 'function' ? rng : new Rng(hashString(`smallres|${choice && choice.id}`));
  const vars = isObj(choice && choice.vars) ? choice.vars : {};
  return fill(resolveText(opt.res, f, R), f, R, vars);
}

